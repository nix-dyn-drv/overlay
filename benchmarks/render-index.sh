#!/usr/bin/env bash
# Renders benchmarks/RESULTS.md into a styled index.html for gh-pages,
# via pandoc -- replaces the previous hand-maintained landing page,
# which drifted out of sync with RESULTS.md across several merged PRs
# before this script existed (see git history on the gh-pages branch).
#
# Usage:
#   nix run nixpkgs#pandoc -- --version   # confirm pandoc is on PATH, or
#   PATH="$(nix build nixpkgs#pandoc --no-link --print-out-paths)/bin:$PATH" \
#     ./benchmarks/render-index.sh > index.html

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"

BODY=$(pandoc "$REPO_ROOT/benchmarks/RESULTS.md" -f gfm -t html --no-highlight --wrap=none --shift-heading-level-by=1)

cat <<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>overlay — dynamic derivations at nixpkgs scale</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<style>
  html { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #fff; color: #222; }
  body { max-width: 860px; margin: 3rem auto; padding: 0 1.5rem; line-height: 1.6; }
  h1 { font-size: 1.6rem; margin-bottom: 0.3rem; }
  h2 { font-size: 1.1rem; margin-top: 2.2rem; border-bottom: 1px solid #eee; padding-bottom: 0.3rem; }
  a { color: #0969da; text-decoration: none; }
  a:hover { text-decoration: underline; }
  table { border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: 0.88rem; }
  th, td { border: 1px solid #d0d7de; padding: 0.5rem 0.7rem; text-align: left; vertical-align: top; }
  th { background: #f6f8fa; }
  code { background: #f6f8fa; padding: 0.1rem 0.35rem; border-radius: 3px; font-size: 0.9em; }
  pre { background: #f6f8fa; padding: 0.8rem 1rem; border-radius: 4px; overflow-x: auto; }
  pre code { background: none; padding: 0; }
  .muted { color: #656d76; font-size: 0.9rem; }
  #top-links { margin-bottom: 1.5rem; }
</style>
</head>
<body>

<h1>overlay</h1>
<p class="muted">Showcasing Nix dynamic derivations against real nixpkgs C/C++ packages, via four independent mechanisms.</p>

<p id="top-links">
  <a href="benchmarks/dashboard/">→ Live benchmark trend chart</a> ·
  <a href="https://github.com/nix-dyn-drv/overlay">→ Source</a> ·
  <a href="https://github.com/nix-dyn-drv/overlay/blob/main/benchmarks/RESULTS.md">→ RESULTS.md on GitHub</a>
</p>

$BODY

<p class="muted">Generated by <code>benchmarks/render-index.sh</code> from
<code>benchmarks/RESULTS.md</code> on every push to <code>main</code> --
never hand-edited.</p>

</body>
</html>
